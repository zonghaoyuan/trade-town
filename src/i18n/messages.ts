export const catalogs: Record<Locale, Record<MessageKey, string>> = {
  en,
  'zh-CN': zhCN,
};

export function translate(
  locale: Locale,
  key: MessageKey,
  variables: MessageVariables = {},
): string {
  const template = (catalogs[locale] as Partial<Record<MessageKey, string>>)[key];
  if (!template) {
    console.warn(`Missing ${locale} translation for "${key}".`);
  }
  return interpolate(template ?? en[key] ?? key, variables);
}

export function interpolate(template: string, variables: MessageVariables = {}) {
  return template.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (token, name: string) =>
    Object.prototype.hasOwnProperty.call(variables, name)
      ? String(variables[name])
      : token,
  );
}
